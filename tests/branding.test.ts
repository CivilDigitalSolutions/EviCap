import { beforeEach, describe, expect, it } from 'vitest';
import { brandingSummary, cleanBranding, contrastRatio, EMPTY_BRANDING, getBranding, isBranded, setBranding } from '../src/lib/branding';
import { buildReportHtml, type ReportInput } from '../src/lib/report';
import type { CaseRecord } from '../src/lib/types';

const PNG = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==';

function report(branding: ReportInput['branding']) {
  return buildReportHtml({
    exportId: 'e1',
    kind: 'case',
    createdAtUtc: '2026-11-16T10:00:00.000Z',
    software: { name: 'EviCap', version: '0.1.0' },
    environment: { extension: '0.1.0', browser: 'Edge', os: 'Windows', userAgent: 'UA', tz: 'Europe/London', tzOffsetMinutes: 0 },
    case: { name: 'Case', reference: 'R-1', investigator: 'I', organisation: 'Case Org', description: '', status: 'open', createdAtUtc: '2026-11-01T00:00:00Z', closedAtUtc: null } as CaseRecord,
    fingerprint: 'sha256:ff',
    auditHead: { seq: 0, hash: 'sha256:ee' },
    auditEvents: 1,
    redactedEvents: 0,
    eventCounts: {},
    exhibits: [],
    visits: [],
    caseNotes: [],
    branding,
  });
}

describe('report branding', () => {
  beforeEach(() => chrome.storage.local.clear());

  it('measures contrast as WCAG does', () => {
    expect(contrastRatio('#000000')).toBeCloseTo(21, 5);
    expect(contrastRatio('#ffffff')).toBeCloseTo(1, 5);
    expect(contrastRatio('#1f4e8c')).toBeGreaterThan(4.5);
  });

  it('tidies text and accepts a dark colour and a PNG logo', () => {
    const b = cleanBranding({ organisation: '  Acme\n  Investigations ', marking: ' OFFICIAL-SENSITIVE ', accent: '#0B5D3B', logoDataUrl: PNG });
    expect(b).toEqual({ organisation: 'Acme Investigations', marking: 'OFFICIAL-SENSITIVE', accent: '#0b5d3b', logoDataUrl: PNG });
    expect(cleanBranding({ accent: '#1f4e8c' }).accent).toBeNull(); // EviCap's own blue is stored as "no colour"
    expect(cleanBranding({ organisation: 'x'.repeat(500) }).organisation).toHaveLength(120);
    expect(isBranded(EMPTY_BRANDING)).toBe(false);
    expect(isBranded(b)).toBe(true);
  });

  it('refuses colours that are hard to read, malformed colours and non-PNG logos', () => {
    expect(() => cleanBranding({ accent: '#ffee99' })).toThrow(/too light/);
    expect(() => cleanBranding({ accent: 'red' })).toThrow(/#rrggbb/);
    expect(() => cleanBranding({ logoDataUrl: 'data:image/svg+xml;base64,PHN2Zz4=' })).toThrow(/PNG/);
    expect(() => cleanBranding({ logoDataUrl: 'https://example.com/logo.png' })).toThrow(/PNG/);
    expect(() => cleanBranding({ logoDataUrl: 'data:image/png;base64,' + 'A'.repeat(500_000) })).toThrow(/too large/);
  });

  it('records the logo in the audit log by its hash, not the image', async () => {
    const s = await brandingSummary(cleanBranding({ organisation: 'Acme', logoDataUrl: PNG }));
    expect(s.logo).toMatch(/^sha256:[0-9a-f]{64}$/);
    expect(JSON.stringify(s)).not.toContain('base64');
  });

  it('stores branding and falls back to none if what is stored is invalid', async () => {
    await setBranding(cleanBranding({ organisation: 'Acme' }));
    expect((await getBranding()).organisation).toBe('Acme');
    await chrome.storage.local.set({ branding: { accent: 'javascript:alert(1)' } });
    expect(await getBranding()).toEqual(EMPTY_BRANDING);
  });

  it('puts the name, logo, colour and marking on the report, escaped', () => {
    const html = report({ organisation: 'Acme <Investigations>', logoDataUrl: PNG, accent: '#0b5d3b', marking: 'OFFICIAL-SENSITIVE' });
    expect(html).toContain('Prepared by <strong>Acme &lt;Investigations&gt;</strong>');
    expect(html).toContain(`<img src="${PNG}"`);
    expect(html).toContain('--accent: #0b5d3b;');
    expect(html).toContain('<div class="marking">OFFICIAL-SENSITIVE</div>');
    expect(html).toContain('Generated by EviCap'); // branding never hides where the report came from
    expect(html).toContain("default-src 'none'");
  });

  it('leaves branding out when there is none, or when it is invalid', () => {
    for (const html of [report(null), report({ accent: '#ffffff' }), report({ logoDataUrl: 'data:text/html,<script>' })]) {
      expect(html).toContain('--accent: #1f4e8c;');
      expect(html).not.toContain('Prepared by');
      expect(html).not.toContain('class="marking"');
      expect(html).not.toMatch(/<img/);
      expect(html).not.toMatch(/<script/i);
    }
  });
});
