import { useEffect, useRef, useState } from 'react';
import {
  BRANDING_LIMITS,
  contrastRatio,
  DEFAULT_ACCENT,
  EMPTY_BRANDING,
  getBranding,
  MIN_ACCENT_CONTRAST,
  prepareLogo,
  type Branding,
} from '@/lib/branding';
import { rpc } from '@/lib/messages';
import { ErrorText } from '@/ui/components';
import { useAction, useLive } from '@/ui/hooks';
import { ProTag, usePlan } from './Plan';

const HEX = /^#[0-9a-f]{6}$/i;

/** Settings → Report branding (Pro, SPEC §9.3). */
export function BrandingCard() {
  const status = usePlan();
  const [saved] = useLive(getBranding, ['state']);
  const [draft, setDraft] = useState<Branding>(EMPTY_BRANDING);
  const [colourText, setColourText] = useState(DEFAULT_ACCENT);
  const [done, setDone] = useState<string | null>(null);
  const { busy, error, run } = useAction();
  const fileRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    if (!saved) return;
    setDraft(saved);
    setColourText(saved.accent ?? DEFAULT_ACCENT);
  }, [saved && JSON.stringify(saved)]);

  if (!status || !saved) return null;
  const pro = status.entitlement.plan === 'pro';
  const set = (patch: Partial<Branding>) => {
    setDone(null);
    setDraft((d) => ({ ...d, ...patch }));
  };
  const colour = colourText.trim().toLowerCase();
  const colourOk = HEX.test(colour);
  const tooLight = colourOk && contrastRatio(colour) < MIN_ACCENT_CONTRAST;
  const accent = colourOk && !tooLight ? colour : (draft.accent ?? DEFAULT_ACCENT);
  const changed = JSON.stringify({ ...draft, accent: colourOk ? colour : draft.accent }) !== JSON.stringify({ ...saved, accent: saved.accent ?? DEFAULT_ACCENT });

  const save = () =>
    run(async () => {
      if (!colourOk) throw new Error('The colour must be written as #rrggbb, for example #0b5d3b.');
      await rpc('saveBranding', { ...draft, accent: colour });
      setDone('Branding saved. It will be used in the next export.');
    });
  const clear = () =>
    run(async () => {
      if (!confirm('Remove the organisation name, logo, colour and marking from future reports?')) return;
      await rpc('saveBranding', EMPTY_BRANDING);
      setDone('Branding removed.');
    });
  const pickLogo = (file: File | undefined) =>
    run(async () => {
      if (!file) return;
      set({ logoDataUrl: await prepareLogo(file) });
      if (fileRef.current) fileRef.current.value = '';
    });

  return (
    <div className="card stack" aria-labelledby="branding-title">
      <div className="row" style={{ justifyContent: 'space-between' }}>
        <h2 id="branding-title">Report branding</h2>
        {!pro && <ProTag />}
      </div>
      <p className="small muted">
        Your organisation's name, logo and colour on the export report, and a protective marking at the top and bottom of every PDF
        page. Branding changes only how the report looks: the integrity sections and the "Generated by EviCap" line stay.
      </p>
      {!pro && (
        <p className="small">
          Branded reports are part of EviCap Pro. Start the free trial or buy Pro under <strong>Plan</strong> below to use them.
        </p>
      )}
      <ErrorText error={error} />
      {done && (
        <p className="small" style={{ color: 'var(--ok)' }} role="status">
          {done}
        </p>
      )}

      <fieldset disabled={!pro || busy} className="stack" style={{ border: 0, padding: 0, margin: 0 }}>
        <label className="field">
          <span>Organisation name, shown as "Prepared by …"</span>
          <input
            value={draft.organisation}
            maxLength={BRANDING_LIMITS.organisation}
            placeholder="e.g. Northshire Trading Standards"
            onChange={(e) => set({ organisation: e.target.value })}
          />
        </label>

        <div className="field">
          <span>Logo</span>
          <div className="row" style={{ gap: 12, flexWrap: 'wrap', alignItems: 'center' }}>
            {draft.logoDataUrl ? (
              <img
                src={draft.logoDataUrl}
                alt="Current logo"
                style={{ maxHeight: 48, maxWidth: 180, background: '#fff', border: '1px solid var(--border)', padding: 4 }}
              />
            ) : (
              <span className="small muted">No logo</span>
            )}
            <input
              ref={fileRef}
              type="file"
              accept="image/png,image/jpeg,image/webp,image/gif"
              aria-label="Choose a logo image"
              onChange={(e) => void pickLogo(e.target.files?.[0])}
            />
            {draft.logoDataUrl && (
              <button type="button" className="btn small" onClick={() => set({ logoDataUrl: null })}>
                Remove logo
              </button>
            )}
          </div>
          <span className="small muted">PNG, JPEG, WebP or GIF. It is resized to at most 900 × 300 pixels and stored as PNG.</span>
        </div>

        <div className="row" style={{ gap: 16, flexWrap: 'wrap', alignItems: 'flex-end' }}>
          <label className="field" style={{ maxWidth: 220 }}>
            <span>Colour for headings and rules</span>
            <div className="row" style={{ gap: 8 }}>
              <input
                type="color"
                aria-label="Pick a colour"
                value={colourOk ? colour : DEFAULT_ACCENT}
                onChange={(e) => {
                  setDone(null);
                  setColourText(e.target.value);
                }}
                style={{ width: 44, height: 34, padding: 2 }}
              />
              <input
                aria-label="Colour as #rrggbb"
                className="mono"
                value={colourText}
                maxLength={7}
                onChange={(e) => {
                  setDone(null);
                  setColourText(e.target.value);
                }}
                style={{ width: 110 }}
              />
            </div>
          </label>
          <button type="button" className="btn small" onClick={() => setColourText(DEFAULT_ACCENT)}>
            Use EviCap blue
          </button>
        </div>
        {!colourOk && <p className="small" style={{ color: 'var(--warn)' }}>Write the colour as #rrggbb.</p>}
        {tooLight && (
          <p className="small" style={{ color: 'var(--warn)' }}>
            That colour is too light to read on white paper. Choose a darker shade.
          </p>
        )}

        <label className="field">
          <span>Protective marking on every page (optional)</span>
          <input
            value={draft.marking}
            maxLength={BRANDING_LIMITS.marking}
            placeholder="e.g. OFFICIAL-SENSITIVE"
            onChange={(e) => set({ marking: e.target.value })}
          />
        </label>
      </fieldset>

      <div className="stack" style={{ gap: 6 }}>
        <span className="small muted">Preview of the report cover</span>
        <ReportCoverPreview branding={{ ...draft, accent }} />
      </div>

      {pro && (
        <div className="row">
          <button type="button" className="btn primary" disabled={busy || !changed || tooLight || !colourOk} onClick={() => void save()}>
            Save branding
          </button>
          <button
            type="button"
            className="btn"
            disabled={busy || JSON.stringify(saved) === JSON.stringify(EMPTY_BRANDING)}
            onClick={() => void clear()}
          >
            Remove branding
          </button>
        </div>
      )}
    </div>
  );
}

/** A small, fixed-colour imitation of the report's first lines (the report is always printed on white). */
function ReportCoverPreview({ branding }: { branding: Branding }) {
  const accent = branding.accent ?? DEFAULT_ACCENT;
  return (
    <div
      aria-hidden="true"
      style={{
        background: '#fff',
        color: '#1c2430',
        border: '1px solid var(--border)',
        borderRadius: 3,
        padding: '14px 18px',
        fontFamily: '"Segoe UI", system-ui, sans-serif',
        fontSize: 12,
      }}
    >
      {branding.marking && (
        <div style={{ textAlign: 'center', fontWeight: 700, letterSpacing: '.06em', fontSize: 11, marginBottom: 8 }}>{branding.marking}</div>
      )}
      <div
        style={{
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'flex-end',
          gap: 12,
          borderBottom: `3px solid ${accent}`,
          paddingBottom: 8,
        }}
      >
        <div>
          <div style={{ textTransform: 'uppercase', letterSpacing: '.08em', fontSize: 10, color: '#5d6877' }}>Evidence report</div>
          <div style={{ fontSize: 18, fontWeight: 600 }}>Case name</div>
          <div style={{ color: '#5d6877' }}>Reference REF/001</div>
          {branding.organisation && (
            <div>
              Prepared by <strong>{branding.organisation}</strong>
            </div>
          )}
        </div>
        {branding.logoDataUrl && <img src={branding.logoDataUrl} alt="" style={{ maxHeight: 40, maxWidth: 140 }} />}
      </div>
      <div style={{ color: accent, fontWeight: 600, fontSize: 13, borderBottom: `1.5px solid ${accent}`, margin: '10px 0 4px', paddingBottom: 2 }}>
        About this report
      </div>
      <div style={{ color: '#5d6877' }}>This report was produced by EviCap…</div>
    </div>
  );
}
